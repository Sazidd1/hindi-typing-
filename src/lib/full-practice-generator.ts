let charIndexCache: Record<string, string[]> | null = null;
let allTargetsCache: string[] | null = null;

function buildCaches() {
  if (charIndexCache && allTargetsCache) return;

  charIndexCache = {};
  allTargetsCache = [];

  keyboardRows.forEach((row, rowIndex) => {
    let rowName = "unknown";
    if (rowIndex === 0) rowName = "number";
    else if (rowIndex === 1) rowName = "top";
    else if (rowIndex === 2) rowName = "home";
    else if (rowIndex === 3) rowName = "bottom";

    row.forEach((key) => {
      if (rowName !== "unknown" && key.en.length === 1) {
        if (key.hi) {
          const targetId = `row:${rowName}:key:${key.en}:normal`;
          allTargetsCache!.push(targetId);
          if (!charIndexCache![key.hi]) charIndexCache![key.hi] = [];
          charIndexCache![key.hi]!.push(targetId);
        }
        if (key.shift) {
          const targetId = `row:${rowName}:key:${key.en}:shift`;
          allTargetsCache!.push(targetId);
          if (!charIndexCache![key.shift]) charIndexCache![key.shift] = [];
          charIndexCache![key.shift]!.push(targetId);
        }
      }
    });
  });
}

const globalLessonSessions: Record<string, string[]> = {};

export function generateFullPracticeSession(lessonSlug?: string) {
  buildCaches();

  const MIN_WORDS = 600;

  const remainingTargets = new Set<string>(allTargetsCache);
  const totalTargets = remainingTargets.size;

  const usedWords = new Set<string>();
  const sessionWords: string[] = [];
  const coveredTargets: string[] = [];

  // Exclude words if lesson is ch-full-practice-3 and we have ch-full-practice-2
  const excludeWords = new Set<string>();
  if (lessonSlug === "ch-full-practice-3" && globalLessonSessions["ch-full-practice-2"]) {
    globalLessonSessions["ch-full-practice-2"].forEach((w) => excludeWords.add(w));
  } else if (lessonSlug === "ch-full-practice-2" && globalLessonSessions["ch-full-practice-3"]) {
    // optional mutual exclusion if they do 3 before 2
    globalLessonSessions["ch-full-practice-3"].forEach((w) => excludeWords.add(w));
  }

  // Filter dictionary to avoid excluded words
  const availableDict = FULL_DICT.filter((w) => !excludeWords.has(w));

  // If exclusion leaves us with too few words, we fallback to full dict to ensure length
  const dictToUse = availableDict.length >= MIN_WORDS ? availableDict : FULL_DICT;
  const shuffledDict = [...dictToUse].sort(() => Math.random() - 0.5);

  let passes = 0;
  while (remainingTargets.size > 0 && passes < 3) {
    passes++;
    let bestWord = null;
    let bestCoveredCount = 0;
    let bestCoveredTargets: string[] = [];

    for (const word of shuffledDict) {
      if (usedWords.has(word)) continue;

      const currentWordCoveredTargets = new Set<string>();

      // Analyze word via exact Remington conversion logic mapped back to physical keys
      for (const hiChar of Object.keys(charIndexCache!)) {
        if (word.includes(hiChar)) {
          const targetIds = charIndexCache![hiChar];
          if (targetIds) {
            for (const tId of targetIds) {
              if (remainingTargets.has(tId)) {
                currentWordCoveredTargets.add(tId);
              }
            }
          }
        }
      }

      if (currentWordCoveredTargets.size > bestCoveredCount) {
        bestCoveredCount = currentWordCoveredTargets.size;
        bestWord = word;
        bestCoveredTargets = Array.from(currentWordCoveredTargets);
      }
    }

    if (bestWord) {
      usedWords.add(bestWord);
      sessionWords.push(bestWord);
      bestCoveredTargets.forEach((t) => {
        remainingTargets.delete(t);
        coveredTargets.push(t);
      });
      passes = 0; // Reset pass count on success
    }
  }

  // To ensure a balanced distribution of the remaining dictionary words,
  // we filter out already used words and shuffle them. Since the dictionary
  // contains a diverse set of short/medium/long words with various matras and conjuncts,
  // this naturally provides a balanced, non-repetitive practice.
  const unusedWords = shuffledDict.filter((w) => !usedWords.has(w));

  for (const word of unusedWords) {
    if (sessionWords.length >= MIN_WORDS) break;
    usedWords.add(word);
    sessionWords.push(word);
  }

  const coveragePercentage = ((totalTargets - remainingTargets.size) / totalTargets) * 100;
  const finalString = sessionWords.join(" ");

  if (lessonSlug) {
    globalLessonSessions[lessonSlug] = sessionWords;
  }

  let overlapCount = 0;
  if (lessonSlug === "ch-full-practice-3" && globalLessonSessions["ch-full-practice-2"]) {
    const list = globalLessonSessions["ch-full-practice-2"];
    overlapCount = sessionWords.filter((w) => list.includes(w)).length;
  } else if (lessonSlug === "ch-full-practice-2" && globalLessonSessions["ch-full-practice-3"]) {
    const list = globalLessonSessions["ch-full-practice-3"];
    overlapCount = sessionWords.filter((w) => list.includes(w)).length;
  }

  const result = {
    totalUniqueWords: sessionWords.length,
    totalCharacters: finalString.length,
    text: finalString,
    coveredTargets,
    remainingTargets: Array.from(remainingTargets),
    coveragePercentage: parseFloat(coveragePercentage.toFixed(2)),
    overlapCount,
  };

  return result;
}
